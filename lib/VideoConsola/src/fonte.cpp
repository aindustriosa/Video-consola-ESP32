const int FONTE_N = 111;


const uint16_t* glifo(uint32_t cp) {
  int lo = 0, hi = FONTE_N - 1;
  while (lo <= hi) {
    int m = (lo + hi) >> 1;
    uint16_t c = FONTE_GLIFOS[m].cp;
    if (c == cp) return FONTE_GLIFOS[m].filas;
    if (c < cp) lo = m + 1; else hi = m - 1;
  }
  return FONTE_GLIFOS[0].filas;  // se non existe, debuxa un espazo
}

